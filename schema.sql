-- Run once in Supabase SQL Editor.
create table if not exists portal_users (
  id bigint generated by default as identity primary key,
  email text unique not null,
  full_name text not null,
  password_hash text not null,
  role text not null check (role in ('FINANCE_ADMIN','TEAM_VIEWER')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists orders (
  id bigint generated by default as identity primary key,
  project_code text not null,
  customer text not null,
  po_number text unique not null,
  quantity integer not null default 0 check (quantity >= 0),
  contract_amount numeric(18,2) not null default 0 check (contract_amount >= 0),
  currency text not null default 'AED',
  advance_received numeric(18,2) not null default 0 check (advance_received >= 0),
  balance_received numeric(18,2) not null default 0 check (balance_received >= 0),
  advance_date date,
  balance_date date,
  delivery_status text not null default 'NOT DELIVERED'
    check (delivery_status in ('NOT DELIVERED','READY FOR DELIVERY','DELIVERED','CANCELLED')),
  remarks text,
  created_by bigint not null references portal_users(id),
  updated_by bigint not null references portal_users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists documents (
  id bigint generated by default as identity primary key,
  order_id bigint not null references orders(id) on delete cascade,
  document_type text not null check (document_type in ('PO','ADVANCE_INVOICE','BALANCE_INVOICE','TAX_INVOICE','OTHER')),
  original_name text not null,
  storage_path text unique not null,
  uploaded_by bigint not null references portal_users(id),
  uploaded_at timestamptz not null default now()
);

create table if not exists audit_log (
  id bigint generated by default as identity primary key,
  user_id bigint not null references portal_users(id),
  order_id bigint references orders(id),
  action text not null,
  details text,
  created_at timestamptz not null default now()
);

create index if not exists idx_orders_customer on orders (customer);
create index if not exists idx_orders_project on orders (project_code);
create index if not exists idx_orders_po on orders (po_number);
create index if not exists idx_documents_order on documents (order_id);
create index if not exists idx_audit_created on audit_log (created_at desc);

-- The Streamlit server uses the service-role key stored in Streamlit Secrets.
-- Never put that key in GitHub or browser code.
alter table portal_users enable row level security;
alter table orders enable row level security;
alter table documents enable row level security;
alter table audit_log enable row level security;
